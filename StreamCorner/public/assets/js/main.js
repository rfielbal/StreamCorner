document.querySelectorAll("[data-toggle-target]").forEach((button) => {
  button.addEventListener("click", () => {
    const targets = resolveTargets(button.getAttribute("data-toggle-target"));
    if (!targets.length) return;

    const group = button.getAttribute("data-toggle-group");
    if (group) {
      document.querySelectorAll(`[data-toggle-group="${group}"]`).forEach((peer) => {
        const peerTargets = resolveTargets(peer.getAttribute("data-toggle-target"));
        peerTargets.forEach((peerTarget) => {
          if (!targets.includes(peerTarget)) {
            peerTarget.classList.remove("is-open");
          }
        });
      });
    }

    const shouldOpen = !targets.every((target) => target.classList.contains("is-open"));
    targets.forEach((target) => {
      target.classList.toggle("is-open", shouldOpen);
    });
    toggleLocks();
  });
});

document.querySelectorAll("[data-close-target]").forEach((button) => {
  button.addEventListener("click", () => {
    const targets = resolveTargets(button.getAttribute("data-close-target"));
    if (!targets.length) return;
    targets.forEach((target) => target.classList.remove("is-open"));
    toggleLocks();
  });
});

document.querySelectorAll("[data-gallery-thumb]").forEach((button) => {
  button.addEventListener("click", () => {
    const mainImage = document.querySelector("[data-gallery-main]");
    if (!mainImage) return;

    const nextSrc = button.getAttribute("data-gallery-src");
    const nextAlt = button.getAttribute("data-gallery-alt") || "";
    if (!nextSrc) return;

    mainImage.src = nextSrc;
    mainImage.alt = nextAlt;

    document.querySelectorAll("[data-gallery-thumb]").forEach((thumb) => {
      thumb.classList.remove("is-active");
    });
    button.classList.add("is-active");
  });
});

document.querySelectorAll("[data-select-group]").forEach((group) => {
  const syncGroup = () => {
    group.querySelectorAll(".radio-card").forEach((card) => {
      const input = card.querySelector('input[type="radio"]');
      card.classList.toggle("is-selected", Boolean(input?.checked));
    });
  };

  group.addEventListener("change", syncGroup);
  syncGroup();
});

document.querySelectorAll("[data-otp-input]").forEach((input, index, list) => {
  input.addEventListener("input", () => {
    input.value = input.value.replace(/\D/g, "").slice(0, 1);
    if (input.value && index < list.length - 1) {
      list[index + 1].focus();
    }
  });

  input.addEventListener("keydown", (event) => {
    if (event.key === "Backspace" && !input.value && index > 0) {
      list[index - 1].focus();
    }
  });
});

document.querySelectorAll("[data-filter-table]").forEach((input) => {
  input.addEventListener("input", () => {
    const selector = input.getAttribute("data-filter-table");
    const table = document.querySelector(selector);
    if (!table) return;

    const term = input.value.trim().toLowerCase();
    table.querySelectorAll("tbody tr").forEach((row) => {
      const text = row.textContent?.toLowerCase() || "";
      row.style.display = text.includes(term) ? "" : "none";
    });
  });
});

document.addEventListener("keydown", (event) => {
  if (event.key !== "Escape") return;
  document.querySelectorAll(".is-open").forEach((panel) => {
    panel.classList.remove("is-open");
  });
  toggleLocks();
});
