const toggleLocks = () => {
  const openPanels = document.querySelectorAll(".is-open");
  const hasOverlayPanel = Array.from(openPanels).some((panel) =>
    panel.matches(".mobile-nav, .catalog-sidebar, .admin-sidebar, .sidebar-backdrop")
  );
  document.body.classList.toggle("is-locked", hasOverlayPanel);
};

const resolveTargets = (selectorValue) =>
  (selectorValue || "")
    .split(",")
    .map((selector) => selector.trim())
    .filter(Boolean)
    .map((selector) => document.querySelector(selector))
    .filter(Boolean);

const syncNavLinks = () => {
  let navSection = document.body.dataset.navSection || "";
  const hashSection = window.location.hash.replace("#", "").trim().toLowerCase();
  if (
    hashSection &&
    Array.from(document.querySelectorAll("[data-nav-item]")).some(
      (link) => link.getAttribute("data-nav-item") === hashSection
    )
  ) {
    navSection = hashSection;
  }

  document.querySelectorAll("[data-nav-item]").forEach((link) => {
    const isActive = link.getAttribute("data-nav-item") === navSection;
    link.classList.toggle("is-active", isActive);
    if (isActive) {
      link.setAttribute("aria-current", "page");
    } else {
      link.removeAttribute("aria-current");
    }
  });
};

const syncNavIcons = () => {
  const navIcon = document.body.dataset.navIcon;
  document.querySelectorAll("[data-nav-icon-item]").forEach((link) => {
    const isActive = link.getAttribute("data-nav-icon-item") === navIcon;
    link.classList.toggle("is-active-icon", isActive);
    if (isActive) {
      link.setAttribute("aria-current", "page");
    } else {
      link.removeAttribute("aria-current");
    }
  });
};

const setNodeText = (selector, value) => {
  const node = document.querySelector(selector);
  if (node && typeof value === "string") {
    node.textContent = value;
  }
};

const setNodeHTML = (selector, value) => {
  const node = document.querySelector(selector);
  if (node && typeof value === "string") {
    node.innerHTML = value;
  }
};

const syncProductPage = () => {
  if (!document.body.hasAttribute("data-product-page")) return;

  const searchParams = new URLSearchParams(window.location.search);
  const requestedProduct = searchParams.get("product") || "";
  const productId = productCatalog[requestedProduct] ? requestedProduct : "command-center";
  const product = productCatalog[productId];

  document.title = `Kinetic Monolith | ${product.pageTitle}`;

  setNodeText("[data-product-pill]", product.pill);
  setNodeHTML("[data-product-title]", product.titleHtml);
  setNodeText("[data-product-summary]", product.summary);
  setNodeText("[data-product-stock-text]", product.stockText);
  setNodeText("[data-product-stock-meta]", product.stockMeta);
  setNodeText("[data-product-price]", product.price);
  setNodeText("[data-product-price-note]", product.priceNote);
  setNodeText("[data-product-feature-eyebrow]", product.featureEyebrow);
  setNodeHTML("[data-product-feature-title]", product.featureTitleHtml);
  setNodeText("[data-product-feature-text]", product.featureText);
  setNodeText("[data-product-specs-intro]", product.specsIntro);
  setNodeText("[data-product-protocol]", product.protocol);
  setNodeText("[data-product-note]", product.note);

  const buyButton = document.querySelector("[data-product-buy]");
  if (buyButton) {
    buyButton.setAttribute("href", product.buyHref);
    buyButton.setAttribute("aria-label", `Ajouter ${product.pageTitle} au panier`);
  }

  const favoriteButton = document.querySelector("[data-product-favorite]");
  if (favoriteButton) {
    favoriteButton.setAttribute("aria-label", `Ajouter ${product.pageTitle} aux favoris`);
  }

  product.summarySpecs.forEach((spec, index) => {
    setNodeText(`[data-product-summary-spec-label="${index}"]`, spec.label);
    setNodeText(`[data-product-summary-spec-value="${index}"]`, spec.value);
  });

  product.featureStats.forEach((stat, index) => {
    setNodeText(`[data-product-feature-stat-text="${index}"]`, stat.text);
    setNodeText(`[data-product-feature-stat-icon="${index}"]`, stat.icon);
  });

  product.specs.forEach((spec, index) => {
    setNodeText(`[data-product-spec-label="${index}"]`, spec.label);
    setNodeText(`[data-product-spec-value="${index}"]`, spec.value);
    setNodeText(`[data-product-spec-text="${index}"]`, spec.text);
  });

  product.requirements.forEach((requirement, index) => {
    setNodeText(`[data-product-requirement-label="${index}"]`, requirement.label);
    setNodeText(`[data-product-requirement-value="${index}"]`, requirement.value);
  });

  const featureImage = document.querySelector("[data-product-feature-image]");
  if (featureImage) {
    featureImage.src = product.featureImage.src;
    featureImage.alt = product.featureImage.alt;
  }

  const galleryMain = document.querySelector("[data-gallery-main]");
  const galleryThumbs = document.querySelectorAll("[data-product-gallery-slot]");
  if (galleryMain && product.gallery.length) {
    galleryMain.src = product.gallery[0].src;
    galleryMain.alt = product.gallery[0].alt;
  }

  galleryThumbs.forEach((thumb, index) => {
    const image = product.gallery[index] || product.gallery[0];
    const thumbImage = thumb.querySelector("img");
    thumb.dataset.gallerySrc = image.src;
    thumb.dataset.galleryAlt = image.alt;
    thumb.classList.toggle("is-active", index === 0);
    thumb.setAttribute("aria-label", image.alt);
    if (thumbImage) {
      thumbImage.src = image.src;
      thumbImage.alt = image.alt;
    }
  });
};

