document.querySelectorAll("[data-toggle-target]").forEach((button) => {
  button.addEventListener("click", () => {
    const targets = resolveTargets(button.getAttribute("data-toggle-target"));
    if (!targets.length) return;

    const group = button.getAttribute("data-toggle-group");
    if (group) {
      document.querySelectorAll(`[data-toggle-group="${group}"]`).forEach((peer) => {
        const peerTargets = resolveTargets(peer.getAttribute("data-toggle-target"));
        peerTargets.forEach((peerTarget) => {
          if (!targets.includes(peerTarget)) {
            peerTarget.classList.remove("is-open");
          }
        });
      });
    }

    const shouldOpen = !targets.every((target) => target.classList.contains("is-open"));
    targets.forEach((target) => {
      target.classList.toggle("is-open", shouldOpen);
    });
    toggleLocks();
  });
});

